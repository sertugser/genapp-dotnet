using GenApp.Application.Persistence;
using GenApp.Domain.Policies;

namespace GenApp.Application.Policies;

// Shared flow of LGAPOL01, LGIPOL01, LGUPOL01 and LGDPOL01. The business programs only check the COMMAREA length; the
// return codes come from the data programs LGAPDB01, LGIPDB01, LGUPDB01 and LGDPDB01, which run the same steps for
// every policy type and differ only in the type table they read and write. A subclass gives the type letter and the
// SET list of its UPDATE statement.
public abstract class PolicyService<TDetails>(IPolicyRepository policies, IUnitOfWork unitOfWork)
    where TDetails : class, IPolicyDetails
{
    // For the type-specific inquiries of a subclass (commercial: 02ICOM, 03ICOM, 05ICOM).
    protected IPolicyRepository Policies { get; } = policies;

    // The POLICY.POLICYTYPE letter of this type (M, H, E, C).
    protected abstract string PolicyType { get; }

    // Copies the fields the legacy UPDATE of the type table sets (lgupdb01.cbl, UPDATE-*-DB2-INFO).
    protected abstract void CopyChanges(TDetails details, TDetails changes);

    // LGAPDB01. The policy number is generated by the database (lgapdb01.cbl:309-311). The policy and type rows are
    // written in one SaveChanges, so in one transaction (ADR 0003 decision 2). The customer is not read first: as in
    // the legacy program, the foreign key rejects a missing customer and that becomes 70 (lgapdb01.cbl:295-298).
    public async Task<OperationResult<PolicyRecord<TDetails>>> AddAsync(
        Policy policy, TDetails details, CancellationToken cancellationToken = default)
    {
        policy.PolicyNumber = 0;
        Policies.Add(policy, details);

        try
        {
            await unitOfWork.SaveChangesAsync(cancellationToken);
        }
        catch (ReferencedRecordNotFoundException)
        {
            return OperationResult<PolicyRecord<TDetails>>.Failure(ReturnCodes.CustomerNotFound);
        }

        return OperationResult<PolicyRecord<TDetails>>.Success(new(policy, details));
    }

    // LGIPDB01: 01 when the customer has no such policy of this type.
    public async Task<OperationResult<PolicyRecord<TDetails>>> InquireAsync(
        int customerNumber, int policyNumber, CancellationToken cancellationToken = default)
    {
        var record = await FindAsync(customerNumber, policyNumber, cancellationToken);
        return record is null
            ? OperationResult<PolicyRecord<TDetails>>.Failure(ReturnCodes.NotFound)
            : OperationResult<PolicyRecord<TDetails>>.Success(record);
    }

    // LGUPDB01. 01 when there is no such policy of this type, 02 when lastChanged no longer matches
    // (lgupdb01.cbl:278, :344-352). The legacy program overwrites both codes with 00 when it closes the cursor; the
    // new system returns them on purpose (ADR 0002 decision 9). PAYMENT and COMMISSION are not in the legacy SET
    // list (lgupdb01.cbl:319-325), so they keep the stored values. Both rows are saved in one SaveChanges: on a
    // conflict the type row is not changed either.
    public async Task<OperationResult<PolicyRecord<TDetails>>> UpdateAsync(
        int customerNumber, int policyNumber, Policy changes, TDetails detailsChanges, DateTime lastChanged,
        CancellationToken cancellationToken = default)
    {
        var record = await FindAsync(customerNumber, policyNumber, cancellationToken);
        if (record is null)
        {
            return OperationResult<PolicyRecord<TDetails>>.Failure(ReturnCodes.NotFound);
        }

        var (policy, details) = record;
        policy.IssueDate = changes.IssueDate;
        policy.ExpiryDate = changes.ExpiryDate;
        policy.BrokerId = changes.BrokerId;
        policy.BrokersReference = changes.BrokersReference;
        CopyChanges(details, detailsChanges);

        Policies.MarkUpdated(policy, lastChanged);

        try
        {
            await unitOfWork.SaveChangesAsync(cancellationToken);
        }
        catch (ConcurrencyConflictException)
        {
            return OperationResult<PolicyRecord<TDetails>>.Failure(ReturnCodes.ConcurrencyConflict);
        }

        return OperationResult<PolicyRecord<TDetails>>.Success(record);
    }

    // LGDPDB01. Returns only the return code: a delete has no value to give back.
    // A missing policy is 90, as the legacy code returns for SQLCODE 100 (lgdpdb01.cbl:198-199). The legacy DELETE
    // ignores the type (:189-194); here a policy of another type is not deleted and 01 is returned
    // (docs/api-design.md section 3).
    public async Task<string> DeleteAsync(int customerNumber, int policyNumber, CancellationToken cancellationToken = default)
    {
        var type = await Policies.FindTypeAsync(customerNumber, policyNumber, cancellationToken);
        if (type is null)
        {
            return ReturnCodes.DatabaseError;
        }

        if (type != PolicyType)
        {
            return ReturnCodes.NotFound;
        }

        var deleted = await Policies.DeleteAsync(customerNumber, policyNumber, cancellationToken);
        return deleted == 0 ? ReturnCodes.DatabaseError : ReturnCodes.Success;
    }

    // The join with the type table leaves out most other types, but a policy of another type can still have a row in
    // this type's table (sample policy 7 is type C with a HOUSE row, db2cre.jcl:901, :1068-1074); the type is checked
    // as well, as docs/api-design.md section 3 states it for inquire and update.
    private async Task<PolicyRecord<TDetails>?> FindAsync(
        int customerNumber, int policyNumber, CancellationToken cancellationToken)
    {
        var record = await Policies.FindAsync<TDetails>(customerNumber, policyNumber, cancellationToken);
        return record?.Policy.PolicyType == PolicyType ? record : null;
    }
}
