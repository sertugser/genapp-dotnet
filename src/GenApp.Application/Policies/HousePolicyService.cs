using GenApp.Application.Persistence;
using GenApp.Domain.Policies;

namespace GenApp.Application.Policies;

// Replaces LGAPOL01, LGIPOL01, LGUPOL01 and LGDPOL01 for house policies (request IDs 01AHOU, 01IHOU, 01UHOU, 01DHOU).
// The business programs only check the COMMAREA length; the return codes come from the data programs LGAPDB01,
// LGIPDB01, LGUPDB01 and LGDPDB01 (legacy-analysis/use-cases/08-11).
public sealed class HousePolicyService(IPolicyRepository policies, IUnitOfWork unitOfWork)
{
    private const string HouseType = "H";

    // LGAPDB01 (08-house-add.md). The policy number is generated by the database (lgapdb01.cbl:309-311). The policy
    // and house rows are written in one SaveChanges, so in one transaction (ADR 0003 decision 2). The customer is not
    // read first: as in the legacy program, the foreign key rejects a missing customer and that becomes 70
    // (lgapdb01.cbl:295-298). The house fields are not checked, as in the legacy program (lgapdb01.cbl:405-425).
    public async Task<OperationResult<PolicyRecord<HousePolicy>>> AddAsync(
        Policy policy, HousePolicy house, CancellationToken cancellationToken = default)
    {
        policy.PolicyNumber = 0;
        policies.Add(policy, house);

        try
        {
            await unitOfWork.SaveChangesAsync(cancellationToken);
        }
        catch (ReferencedRecordNotFoundException)
        {
            return OperationResult<PolicyRecord<HousePolicy>>.Failure(ReturnCodes.CustomerNotFound);
        }

        return OperationResult<PolicyRecord<HousePolicy>>.Success(new(policy, house));
    }

    // LGIPDB01 (09-house-inquire.md): 01 when the customer has no such house policy (lgipdb01.cbl:510-514).
    public async Task<OperationResult<PolicyRecord<HousePolicy>>> InquireAsync(
        int customerNumber, int policyNumber, CancellationToken cancellationToken = default)
    {
        var record = await FindHouseAsync(customerNumber, policyNumber, cancellationToken);
        return record is null
            ? OperationResult<PolicyRecord<HousePolicy>>.Failure(ReturnCodes.NotFound)
            : OperationResult<PolicyRecord<HousePolicy>>.Success(record);
    }

    // LGUPDB01 (10-house-update.md). 01 when there is no such house policy, 02 when lastChanged no longer matches
    // (lgupdb01.cbl:278, :344-352). The legacy program overwrites both codes with 00 when it closes the cursor; the
    // new system returns them on purpose (ADR 0002 decision 9). PAYMENT and COMMISSION are not in the legacy SET
    // list (lgupdb01.cbl:319-325), so they keep the stored values. Both rows are saved in one SaveChanges: on a
    // conflict the house row is not changed either.
    public async Task<OperationResult<PolicyRecord<HousePolicy>>> UpdateAsync(
        int customerNumber, int policyNumber, Policy changes, HousePolicy houseChanges, DateTime lastChanged,
        CancellationToken cancellationToken = default)
    {
        var record = await FindHouseAsync(customerNumber, policyNumber, cancellationToken);
        if (record is null)
        {
            return OperationResult<PolicyRecord<HousePolicy>>.Failure(ReturnCodes.NotFound);
        }

        var (policy, house) = record;
        policy.IssueDate = changes.IssueDate;
        policy.ExpiryDate = changes.ExpiryDate;
        policy.BrokerId = changes.BrokerId;
        policy.BrokersReference = changes.BrokersReference;

        // lgupdb01.cbl:431-442
        house.PropertyType = houseChanges.PropertyType;
        house.Bedrooms = houseChanges.Bedrooms;
        house.Value = houseChanges.Value;
        house.HouseName = houseChanges.HouseName;
        house.HouseNumber = houseChanges.HouseNumber;
        house.Postcode = houseChanges.Postcode;

        policies.MarkUpdated(policy, lastChanged);

        try
        {
            await unitOfWork.SaveChangesAsync(cancellationToken);
        }
        catch (ConcurrencyConflictException)
        {
            return OperationResult<PolicyRecord<HousePolicy>>.Failure(ReturnCodes.ConcurrencyConflict);
        }

        return OperationResult<PolicyRecord<HousePolicy>>.Success(record);
    }

    // LGDPDB01 (11-house-delete.md). Returns only the return code: a delete has no value to give back.
    // A missing policy is 90, as the legacy code returns for SQLCODE 100 (lgdpdb01.cbl:198-199). The legacy DELETE
    // ignores the type (:189-194); here a policy of another type is not deleted and 01 is returned
    // (docs/api-design.md section 3).
    public async Task<string> DeleteAsync(int customerNumber, int policyNumber, CancellationToken cancellationToken = default)
    {
        var type = await policies.FindTypeAsync(customerNumber, policyNumber, cancellationToken);
        if (type is null)
        {
            return ReturnCodes.DatabaseError;
        }

        if (type != HouseType)
        {
            return ReturnCodes.NotFound;
        }

        var deleted = await policies.DeleteAsync(customerNumber, policyNumber, cancellationToken);
        return deleted == 0 ? ReturnCodes.DatabaseError : ReturnCodes.Success;
    }

    // The join with the house table leaves out most other types (lgipdb01.cbl:469-475), but a policy of another type
    // can still have a house row (sample policy 7, db2cre.jcl:901, :1068-1074); the type is checked as well, as
    // docs/api-design.md section 3 states it for inquire and update.
    private async Task<PolicyRecord<HousePolicy>?> FindHouseAsync(
        int customerNumber, int policyNumber, CancellationToken cancellationToken)
    {
        var record = await policies.FindAsync<HousePolicy>(customerNumber, policyNumber, cancellationToken);
        return record?.Policy.PolicyType == HouseType ? record : null;
    }
}
