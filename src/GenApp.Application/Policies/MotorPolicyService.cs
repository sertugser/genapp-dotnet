using GenApp.Application.Persistence;
using GenApp.Domain.Policies;

namespace GenApp.Application.Policies;

// Replaces LGAPOL01, LGIPOL01, LGUPOL01 and LGDPOL01 for motor policies (request IDs 01AMOT, 01IMOT, 01UMOT, 01DMOT).
// The business programs only check the COMMAREA length; the return codes come from the data programs LGAPDB01,
// LGIPDB01, LGUPDB01 and LGDPDB01 (legacy-analysis/use-cases/04-07).
public sealed class MotorPolicyService(IPolicyRepository policies, IUnitOfWork unitOfWork)
{
    private const string MotorType = "M";

    // LGAPDB01 (04-motor-add.md). The policy number is generated by the database (lgapdb01.cbl:309-311). The policy
    // and motor rows are written in one SaveChanges, so in one transaction (ADR 0003 decision 2). The customer is not
    // read first: as in the legacy program, the foreign key rejects a missing customer and that becomes 70
    // (lgapdb01.cbl:295-298).
    public async Task<OperationResult<PolicyRecord<MotorPolicy>>> AddAsync(
        Policy policy, MotorPolicy motor, CancellationToken cancellationToken = default)
    {
        policy.PolicyNumber = 0;
        policies.Add(policy, motor);

        try
        {
            await unitOfWork.SaveChangesAsync(cancellationToken);
        }
        catch (ReferencedRecordNotFoundException)
        {
            return OperationResult<PolicyRecord<MotorPolicy>>.Failure(ReturnCodes.CustomerNotFound);
        }

        return OperationResult<PolicyRecord<MotorPolicy>>.Success(new(policy, motor));
    }

    // LGIPDB01 (05-motor-inquire.md): 01 when the customer has no such motor policy (lgipdb01.cbl:608-612).
    public async Task<OperationResult<PolicyRecord<MotorPolicy>>> InquireAsync(
        int customerNumber, int policyNumber, CancellationToken cancellationToken = default)
    {
        var record = await FindMotorAsync(customerNumber, policyNumber, cancellationToken);
        return record is null
            ? OperationResult<PolicyRecord<MotorPolicy>>.Failure(ReturnCodes.NotFound)
            : OperationResult<PolicyRecord<MotorPolicy>>.Success(record);
    }

    // LGUPDB01 (06-motor-update.md). 01 when there is no such motor policy, 02 when lastChanged no longer matches
    // (lgupdb01.cbl:278, :344-352). The legacy program overwrites both codes with 00 when it closes the cursor; the
    // new system returns them on purpose (ADR 0002 decision 9). PAYMENT and COMMISSION are not in the legacy SET
    // list (lgupdb01.cbl:319-325), so they keep the stored values. Both rows are saved in one SaveChanges: on a
    // conflict the motor row is not changed either.
    public async Task<OperationResult<PolicyRecord<MotorPolicy>>> UpdateAsync(
        int customerNumber, int policyNumber, Policy changes, MotorPolicy motorChanges, DateTime lastChanged,
        CancellationToken cancellationToken = default)
    {
        var record = await FindMotorAsync(customerNumber, policyNumber, cancellationToken);
        if (record is null)
        {
            return OperationResult<PolicyRecord<MotorPolicy>>.Failure(ReturnCodes.NotFound);
        }

        var (policy, motor) = record;
        policy.IssueDate = changes.IssueDate;
        policy.ExpiryDate = changes.ExpiryDate;
        policy.BrokerId = changes.BrokerId;
        policy.BrokersReference = changes.BrokersReference;

        // lgupdb01.cbl:469-483
        motor.Make = motorChanges.Make;
        motor.Model = motorChanges.Model;
        motor.Value = motorChanges.Value;
        motor.RegNumber = motorChanges.RegNumber;
        motor.Colour = motorChanges.Colour;
        motor.Cc = motorChanges.Cc;
        motor.YearOfManufacture = motorChanges.YearOfManufacture;
        motor.Premium = motorChanges.Premium;
        motor.Accidents = motorChanges.Accidents;

        policies.MarkUpdated(policy, lastChanged);

        try
        {
            await unitOfWork.SaveChangesAsync(cancellationToken);
        }
        catch (ConcurrencyConflictException)
        {
            return OperationResult<PolicyRecord<MotorPolicy>>.Failure(ReturnCodes.ConcurrencyConflict);
        }

        return OperationResult<PolicyRecord<MotorPolicy>>.Success(record);
    }

    // LGDPDB01 (07-motor-delete.md). Returns only the return code: a delete has no value to give back.
    // A missing policy is 90, as the legacy code returns for SQLCODE 100 (lgdpdb01.cbl:198-199). The legacy DELETE
    // ignores the type (:189-194); here a policy of another type is not deleted and 01 is returned
    // (docs/api-design.md section 3).
    public async Task<string> DeleteAsync(int customerNumber, int policyNumber, CancellationToken cancellationToken = default)
    {
        var type = await policies.FindTypeAsync(customerNumber, policyNumber, cancellationToken);
        if (type is null)
        {
            return ReturnCodes.DatabaseError;
        }

        if (type != MotorType)
        {
            return ReturnCodes.NotFound;
        }

        var deleted = await policies.DeleteAsync(customerNumber, policyNumber, cancellationToken);
        return deleted == 0 ? ReturnCodes.DatabaseError : ReturnCodes.Success;
    }

    // The join with the motor table already leaves out other types (lgipdb01.cbl:564-569); the type is checked as
    // well, as docs/api-design.md section 3 states it for inquire and update.
    private async Task<PolicyRecord<MotorPolicy>?> FindMotorAsync(
        int customerNumber, int policyNumber, CancellationToken cancellationToken)
    {
        var record = await policies.FindAsync<MotorPolicy>(customerNumber, policyNumber, cancellationToken);
        return record?.Policy.PolicyType == MotorType ? record : null;
    }
}
